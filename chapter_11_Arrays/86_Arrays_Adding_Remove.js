let arr = [1, 2, 3];
console.log(arr);

//Add to end
arr.push(4);
console.log(arr);

//Remove from end
arr.pop();
console.log(arr);

arr.push(5, 6);
console.log(arr);

//Add at beginning
arr.unshift(0);
console.log(arr);

//Remove from beginning
arr.shift();
console.log(arr);


console.log(arr);
