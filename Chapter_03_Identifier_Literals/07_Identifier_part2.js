var name = "Sree";

var firstName = "Sree";
var lastName = "Vidya"; //camelcase

var first_name = "sree"; //Snakecase

// PascalCase - starts with uppercase, used for classes/constructors
var FirstName = "Sree";
var CustomerDetails = "Data";

// SCREAMING_SNAKE_CASE - all uppercase with underscores, used for constants
var FIRST_NAME = "SREE";
var MAX_VALUE = 100;

// Hungarian notation - prefix indicates type (older style)
var strName = "Sree";
var nAge = 25;
var bIsActive = true;

// Examples of each naming convention
console.log("camelCase:", firstName);
console.log("snake_case:", first_name);
console.log("PascalCase:", FirstName);
console.log("SCREAMING_SNAKE_CASE:", FIRST_NAME);
console.log("Hungarian notation:", strName);

